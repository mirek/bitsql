// Regenerates src/core/types/cp1252_best_fit.mbt from the oracle: for every
// UTF-16 code unit v, CAST(CAST(NCHAR(v) COLLATE <c> AS varchar(4)) AS
// varbinary(4)) under three CP1252 collations (they must agree). Units with
// an exact CP1252 mapping and units that become '?' are left out; the rest
// is SQL Server's (Windows) best-fit table.
//
//   npm run oracle:start && node gen/cp1252-best-fit.mjs
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { capture } from '../src/capture-core.mjs'
import { connect, close } from '../src/client.mjs'
import { oracleTarget } from '../src/runner.mjs'
import { repoDir } from '../src/env.mjs'

const collations = ['SQL_Latin1_General_CP1_CI_AS', 'Latin1_General_100_CI_AS', 'Latin1_General_BIN2']
const high = [0x20AC, 0, 0x201A, 0x0192, 0x201E, 0x2026, 0x2020, 0x2021, 0x02C6, 0x2030, 0x0160, 0x2039, 0x0152, 0, 0x017D, 0, 0, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014, 0x02DC, 0x2122, 0x0161, 0x203A, 0x0153, 0, 0x017E, 0x0178]
const exact = new Map()
for (let b = 0; b < 256; b++) exact.set(b >= 0x80 && b <= 0x9F && high[b - 0x80] ? high[b - 0x80] : b, b)

const target = await oracleTarget()
const session = await target.session()
const connection = await connect(session.config)
const tables = []
for (const c of collations) {
  const sql = `WITH n AS (SELECT TOP 65536 ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) - 1 AS v FROM sys.all_objects a CROSS JOIN sys.all_objects b)
SELECT v, CAST(CAST(NCHAR(v) COLLATE ${c} AS varchar(4)) AS varbinary(4)) AS b FROM n ORDER BY v`
  const r = await capture(connection, { kind: 'batch', sql })
  if (r.errors.length) throw new Error(r.errors[0].message)
  tables.push(r.sets[0].rows.map(([v, b]) => [Number(v), [...b]]))
}
await close(connection)
const version = (await (async () => target.server.version)())

const pairs = []
for (let u = 0; u < 65536; u++) {
  const bytes = tables.map(t => t[u][1].join(','))
  if (new Set(bytes).size !== 1) throw new Error(`collations disagree at U+${u.toString(16)}`)
  const b = tables[0][u][1]
  if (b.length !== 1) throw new Error(`U+${u.toString(16)} converts to ${b.length} bytes`)
  if (exact.has(u)) {
    if (exact.get(u) !== b[0]) throw new Error(`exact mapping differs at U+${u.toString(16)}`)
  } else if (b[0] !== 0x3F) pairs.push([u, b[0]])
}

const hex = (n, w) => '0x' + n.toString(16).toUpperCase().padStart(w, '0')
const lines = [
  `// GENERATED by harness/gen/cp1252-best-fit.mjs from SQL Server ${version}: for`,
  '// every UTF-16 code unit v, CAST(CAST(NCHAR(v) COLLATE <c> AS varchar(4)) AS',
  '// varbinary(4)) under SQL_Latin1_General_CP1_CI_AS, Latin1_General_100_CI_AS',
  '// and Latin1_General_BIN2 (identical). 256 units map exactly (cp1252.mbt), the',
  `// ${pairs.length} below map by Windows "best fit", every other unit (surrogate halves`,
  "// included) becomes '?' (0x3F).",
  '',
  '///|',
  '/// Pairs (UTF-16 code unit, CP1252 byte), sorted by code unit.',
  'let cp1252_best_fit : FixedArray[(Int, Int)] = [',
]
for (let i = 0; i < pairs.length; i += 6) {
  lines.push('  ' + pairs.slice(i, i + 6).map(([u, b]) => `(${hex(u, 4)}, ${hex(b, 2)})`).join(', ') + ',')
}
lines.push(']')
writeFileSync(join(repoDir, 'src/core/types/cp1252_best_fit.mbt'), lines.join('\n') + '\n')
console.log(`wrote ${pairs.length} best-fit pairs`)
