-- Firing order of triggers on tables changed by cascading referential
-- actions: reverse depth-first order of the cascade tree, siblings by
-- foreign key object_id (not creation order: the second part wraps the
-- object id sequence, so later foreign keys get smaller ids). No trigger
-- fires before the DDL, so object ids match SQL Server's.
-- @step setup
