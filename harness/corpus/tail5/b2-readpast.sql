-- READPAST outside READ COMMITTED / REPEATABLE READ: 650 at run time when
-- the table is read (after COLMETADATA for a SELECT; DONE 253 for DML and
-- assignments), ending the batch and rolling back an open transaction. The
-- isolation is the table's hint, else the session level; RCSI is fine.
-- UPDATE/DELETE targets ignore a READ UNCOMMITTED session and pass a WHERE
-- that is exactly the clustered primary key = constant/variable. An INSERT
-- target with READPAST is 4102 for the whole batch.
-- @step setup
CREATE TABLE hp (id int NOT NULL CONSTRAINT PK_hp PRIMARY KEY, v int, w int CONSTRAINT UQ_hp UNIQUE); INSERT INTO hp VALUES (1,1,1),(2,2,2); CREATE TABLE hq (id int, v int); INSERT INTO hq VALUES (1,1);
-- @step batch
SELECT 1 AS a; SELECT COUNT(*) AS n FROM hp WITH (NOLOCK, READPAST); SELECT 2 AS b
-- @step batch
SELECT COUNT(*) AS n FROM hp WITH (READPAST, HOLDLOCK)
-- @step batch
SELECT COUNT(*) AS n FROM hp WITH (READPAST, READUNCOMMITTED)
-- @step batch
SELECT COUNT(*) AS n FROM hp WITH (READPAST, REPEATABLEREAD)
-- @step batch
SELECT COUNT(*) AS n FROM hp WITH (READPAST, READCOMMITTED)
-- @step batch
SELECT COUNT(*) AS n FROM hp WITH (READPAST, UPDLOCK)
-- @step batch
SELECT v FROM hp WITH (READPAST, SERIALIZABLE) WHERE id = 1
-- @step batch
SELECT v FROM hp WITH (READPAST, SERIALIZABLE) WHERE 1 = 0
-- @step batch
SELECT 1 AS a; SELECT id FROM hp h WHERE EXISTS (SELECT 1 FROM hq WITH (READPAST, SERIALIZABLE) WHERE hq.id = h.id); SELECT 2 AS b
-- @step batch
SELECT 1 AS a; SELECT h.id FROM hq h JOIN hp g WITH (READPAST, SERIALIZABLE) ON g.id = h.id; SELECT 2 AS b
-- @step batch
DECLARE @n int; SELECT 1 AS a; SELECT @n = COUNT(*) FROM hp WITH (NOLOCK, READPAST); SELECT 2 AS b
-- @step batch
BEGIN TRY SELECT COUNT(*) AS n FROM hp WITH (NOLOCK, READPAST) END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS e END CATCH
-- @step batch
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE; SELECT COUNT(*) AS n FROM hp WITH (READPAST)
-- @step batch
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE; SELECT COUNT(*) AS n FROM hp WITH (READPAST, READCOMMITTED); SET TRANSACTION ISOLATION LEVEL READ COMMITTED
-- @step batch
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; SELECT v FROM hp WITH (READPAST) WHERE id = 1
-- @step batch
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; UPDATE hp WITH (READPAST) SET v = 3; SET TRANSACTION ISOLATION LEVEL READ COMMITTED
-- @step batch
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE; DELETE hp WITH (READPAST) WHERE id = 9
-- @step batch
SET TRANSACTION ISOLATION LEVEL READ COMMITTED
-- @step batch
SELECT 1 AS a; UPDATE hp WITH (READPAST, SERIALIZABLE) SET v = 3; SELECT 2 AS b
-- @step batch
SELECT 1 AS a; DELETE hp WITH (READPAST, SERIALIZABLE); SELECT 2 AS b
-- @step batch
UPDATE hp WITH (READPAST, SERIALIZABLE) SET v = 3 WHERE id = 7
-- @step batch
DECLARE @i int = 1; UPDATE hp WITH (READPAST, SERIALIZABLE) SET v = 3 WHERE id = @i
-- @step batch
UPDATE hp WITH (READPAST, SERIALIZABLE) SET v = 3 WHERE w = 1
-- @step batch
UPDATE hp WITH (READPAST, SERIALIZABLE) SET v = 3 WHERE id = 1 AND v = 3
-- @step batch
DELETE FROM hp WITH (READPAST, SERIALIZABLE) WHERE id IN (7, 8)
-- @step batch
UPDATE h SET v = 4 FROM hp h WITH (READPAST, SERIALIZABLE) WHERE h.id = 1
-- @step batch
UPDATE hq WITH (READPAST, SERIALIZABLE) SET v = 3 WHERE id = 7
-- @step batch
UPDATE hp WITH (READPAST, REPEATABLEREAD) SET v = 3
-- @step batch
BEGIN TRY UPDATE hp WITH (READPAST, SERIALIZABLE) SET v = 3 END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS e, @@TRANCOUNT AS t END CATCH
