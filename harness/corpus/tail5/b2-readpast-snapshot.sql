-- READPAST under SNAPSHOT isolation (database allows it): 650 unless a
-- READCOMMITTEDLOCK / READCOMMITTED / REPEATABLEREAD hint; UPDLOCK or
-- HOLDLOCK do not help; an UPDATE target fails too. Under
-- READ_COMMITTED_SNAPSHOT READPAST is allowed.
-- @step setup
CREATE TABLE hp (id int NOT NULL CONSTRAINT PK_hp PRIMARY KEY, v int); INSERT INTO hp VALUES (1,1),(2,2);
-- @step setup
DECLARE @d nvarchar(200) = N'ALTER DATABASE ' + QUOTENAME(DB_NAME()) + N' SET ALLOW_SNAPSHOT_ISOLATION ON'; EXEC (@d)
-- @step batch
SET TRANSACTION ISOLATION LEVEL SNAPSHOT; SELECT COUNT(*) AS n FROM hp WITH (READPAST, UPDLOCK)
-- @step batch
SET TRANSACTION ISOLATION LEVEL SNAPSHOT; SELECT COUNT(*) AS n FROM hp WITH (READPAST, HOLDLOCK)
-- @step batch
SET TRANSACTION ISOLATION LEVEL SNAPSHOT; SELECT COUNT(*) AS n FROM hp WITH (READPAST, READCOMMITTEDLOCK)
-- @step batch
SET TRANSACTION ISOLATION LEVEL SNAPSHOT; SELECT COUNT(*) AS n FROM hp WITH (READPAST)
-- @step batch
SET TRANSACTION ISOLATION LEVEL SNAPSHOT; UPDATE hp WITH (READPAST) SET v = 5
-- @step batch
SET TRANSACTION ISOLATION LEVEL READ COMMITTED
-- @step setup
DECLARE @d nvarchar(200) = N'ALTER DATABASE ' + QUOTENAME(DB_NAME()) + N' SET READ_COMMITTED_SNAPSHOT ON WITH ROLLBACK IMMEDIATE'; EXEC (@d)
-- @step batch
SELECT COUNT(*) AS n FROM hp WITH (READPAST)
-- @step batch
UPDATE hp WITH (READPAST) SET v = 6
