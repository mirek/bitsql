-- Conflicting cursor options are batch compile errors 1048 whose message
-- names a fixed pair; mixing ISO and T-SQL syntax is 1049 at line 0.
-- @step setup
CREATE TABLE t (id int NOT NULL PRIMARY KEY);
-- @step batch
DECLARE x0 CURSOR LOCAL STATIC DYNAMIC FOR SELECT id FROM t;
-- @step batch
DECLARE x1 CURSOR LOCAL DYNAMIC STATIC FOR SELECT id FROM t;
-- @step batch
DECLARE x2 CURSOR LOCAL FAST_FORWARD KEYSET FOR SELECT id FROM t;
-- @step batch
DECLARE x3 CURSOR LOCAL FAST_FORWARD OPTIMISTIC FOR SELECT id FROM t;
-- @step batch
DECLARE x4 CURSOR LOCAL OPTIMISTIC READ_ONLY FOR SELECT id FROM t;
-- @step batch
DECLARE x5 CURSOR LOCAL READ_ONLY SCROLL_LOCKS FOR SELECT id FROM t;
-- @step batch
DECLARE x6 CURSOR LOCAL GLOBAL FOR SELECT id FROM t;
-- @step batch
DECLARE x7 CURSOR FAST_FORWARD FOR SELECT id FROM t FOR UPDATE;
-- @step batch
DECLARE x8 INSENSITIVE CURSOR FOR SELECT id FROM t FOR UPDATE;
-- @step batch
SELECT 1 AS before_conflict;
DECLARE x9 CURSOR LOCAL STATIC SCROLL_LOCKS FOR SELECT id FROM t;
-- @step batch
SELECT 1 AS before_mix;
DECLARE x10 INSENSITIVE CURSOR STATIC FOR SELECT id FROM t;
-- @step batch
DECLARE x11 CURSOR LOCAL STATIC OPTIMISTIC FOR SELECT id FROM t;
DECLARE x12 CURSOR LOCAL FAST_FORWARD READ_ONLY FORWARD_ONLY FOR SELECT id FROM t;
DECLARE x13 CURSOR LOCAL STATIC STATIC FOR SELECT id FROM t;
SELECT name, properties FROM sys.dm_exec_cursors(@@SPID) ORDER BY name;
