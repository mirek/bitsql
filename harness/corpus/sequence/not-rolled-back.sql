-- Sequence values are not rolled back; ALTER SEQUENCE RESTART.
-- @step setup
CREATE SEQUENCE dbo.s START WITH 1;
-- @step batch
BEGIN TRAN; SELECT NEXT VALUE FOR dbo.s AS a; ROLLBACK;
SELECT NEXT VALUE FOR dbo.s AS b;
ALTER SEQUENCE dbo.s RESTART WITH 50;
SELECT NEXT VALUE FOR dbo.s AS c;
ALTER SEQUENCE dbo.s RESTART;
SELECT NEXT VALUE FOR dbo.s AS d;
