-- A FOR JSON subquery is embedded raw by JSON_OBJECT/JSON_ARRAY/JSON_MODIFY,
-- except with WITHOUT_ARRAY_WRAPPER (a plain, escaped string). bitsql does
-- not bind FOR JSON in subqueries yet.
SELECT JSON_OBJECT('a':(SELECT 1 AS x FOR JSON PATH)) a, JSON_OBJECT('a':(SELECT 1 AS x FOR JSON PATH, WITHOUT_ARRAY_WRAPPER)) b;
SELECT JSON_ARRAY((SELECT 1 AS x FOR JSON PATH, WITHOUT_ARRAY_WRAPPER)) c, JSON_ARRAY((SELECT 1 AS x FOR JSON PATH)) d;
SELECT JSON_MODIFY(N'{"a":1}', '$.a', (SELECT 1 AS x FOR JSON PATH)) c;
