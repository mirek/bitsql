-- SET ANSI_PADDING / CONCAT_NULL_YIELDS_NULL / QUOTED_IDENTIFIER OFF and
-- NUMERIC_ROUNDABORT, ARITHABORT, ARITHIGNORE: SESSIONPROPERTY and
-- @@OPTIONS follow them; statements their non-default values do not
-- affect run normally (nvarchar/int columns under ANSI_PADDING OFF,
-- CONCAT(), single-quoted strings under QUOTED_IDENTIFIER OFF, integer
-- arithmetic under NUMERIC_ROUNDABORT ON).
-- @step setup
CREATE TABLE dbo.t(id int, s nvarchar(10));
-- @step batch
SET ANSI_PADDING OFF; SELECT SESSIONPROPERTY('ANSI_PADDING'), @@OPTIONS;
CREATE TABLE dbo.p(n nvarchar(5), i int); INSERT dbo.p VALUES (N'a  ', 1); SELECT DATALENGTH(n), i FROM dbo.p;
SELECT name, is_ansi_padded FROM sys.columns WHERE object_id = OBJECT_ID('dbo.p') ORDER BY column_id;
SET ANSI_PADDING ON; SELECT SESSIONPROPERTY('ANSI_PADDING'), @@OPTIONS
-- @step batch
SET CONCAT_NULL_YIELDS_NULL OFF; SELECT SESSIONPROPERTY('CONCAT_NULL_YIELDS_NULL'), @@OPTIONS, CONCAT('a', NULL, 'b'), 1 + 2;
SET CONCAT_NULL_YIELDS_NULL ON; SELECT SESSIONPROPERTY('CONCAT_NULL_YIELDS_NULL'), @@OPTIONS
-- @step batch
SET QUOTED_IDENTIFIER OFF; SELECT SESSIONPROPERTY('QUOTED_IDENTIFIER'), @@OPTIONS, 'x' AS [y]; SET QUOTED_IDENTIFIER ON;
SELECT SESSIONPROPERTY('QUOTED_IDENTIFIER'), @@OPTIONS, 1 AS "z"
-- @step batch
SET QUOTED_IDENTIFIER OFF
-- @step batch
SELECT SESSIONPROPERTY('QUOTED_IDENTIFIER'), 'still off' AS [v]
-- @step batch
SET QUOTED_IDENTIFIER ON
-- @step batch
SET NUMERIC_ROUNDABORT ON; SELECT SESSIONPROPERTY('NUMERIC_ROUNDABORT'), @@OPTIONS, 7 / 2, LEN(N'abc');
SET NUMERIC_ROUNDABORT OFF; SELECT SESSIONPROPERTY('NUMERIC_ROUNDABORT'), @@OPTIONS
-- @step batch
SET ARITHABORT OFF; SELECT SESSIONPROPERTY('ARITHABORT'), @@OPTIONS; SET ARITHABORT ON;
SET ARITHIGNORE ON; SELECT @@OPTIONS; SET ARITHIGNORE OFF; SELECT @@OPTIONS
-- @step batch
EXEC sp_executesql N'SET ANSI_PADDING OFF; SET CONCAT_NULL_YIELDS_NULL OFF; SELECT @@OPTIONS'; SELECT @@OPTIONS
