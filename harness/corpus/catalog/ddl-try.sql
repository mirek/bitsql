-- DDL errors inside TRY: most are caught after a completion carrying the
-- statement's CurCmd (198/216/200/199); 4902 and 1779/1750 are not caught
-- and end the batch. Outside TRY the same errors end the batch.
-- @step setup
CREATE TABLE dbo.a (id int NOT NULL CONSTRAINT pk_a PRIMARY KEY, x int NULL, y int NULL CONSTRAINT ck CHECK (y > 0));
INSERT INTO dbo.a VALUES (1, 1, 1), (2, 1, 1);
-- @step batch
BEGIN TRY CREATE TABLE dbo.a (id int); END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY ALTER TABLE dbo.a DROP COLUMN nosuch; END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY ALTER TABLE dbo.a DROP COLUMN y; END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n, ERROR_MESSAGE() AS m; END CATCH
-- @step batch
BEGIN TRY ALTER TABLE dbo.a ADD CONSTRAINT uq UNIQUE (x); END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY ALTER TABLE dbo.a ADD CONSTRAINT ck2 CHECK (x > 5); END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY ALTER TABLE dbo.nosuch ADD z int; END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY ALTER TABLE dbo.a DROP CONSTRAINT nosuch; END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY CREATE INDEX ix ON dbo.a (nosuch); END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY CREATE UNIQUE INDEX ix ON dbo.a (x); END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
BEGIN TRY DROP TABLE dbo.nosuch; END TRY BEGIN CATCH SELECT ERROR_NUMBER() AS n; END CATCH
-- @step batch
