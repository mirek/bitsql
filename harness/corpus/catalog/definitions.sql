-- Normalized definition text of DEFAULT / CHECK / computed / filter
-- expressions (sys.*_constraints.definition, INFORMATION_SCHEMA COLUMN_DEFAULT).
-- @step setup
CREATE TABLE dbo.d (
 a int NULL CONSTRAINT d1 DEFAULT 0,
 b int NULL CONSTRAINT d2 DEFAULT -1,
 c nvarchar(10) NULL CONSTRAINT d3 DEFAULT N'x''y',
 d varchar(10) NULL CONSTRAINT d4 DEFAULT 'abc',
 e datetime NULL CONSTRAINT d5 DEFAULT GETDATE(),
 f datetime2 NULL CONSTRAINT d6 DEFAULT SYSUTCDATETIME(),
 g uniqueidentifier NULL CONSTRAINT d7 DEFAULT NEWID(),
 h bit NULL CONSTRAINT d8 DEFAULT 1,
 i decimal(9,2) NULL CONSTRAINT d9 DEFAULT 1.50,
 j float NULL CONSTRAINT d10 DEFAULT 1e3,
 k int NULL CONSTRAINT d11 DEFAULT (1 + 2) * 3,
 l datetime NULL CONSTRAINT d12 DEFAULT CURRENT_TIMESTAMP,
 m varbinary(4) NULL CONSTRAINT d13 DEFAULT 0x0A,
 n int NULL CONSTRAINT d14 DEFAULT NULL,
 p int NULL CONSTRAINT d15 DEFAULT (5),
 q money NULL CONSTRAINT d16 DEFAULT $1.5,
 r int NULL CONSTRAINT d17 DEFAULT CAST('1' AS int),
 s int NULL CONSTRAINT d18 DEFAULT CONVERT(int, '2'),
 t nvarchar(10) NULL CONSTRAINT d19 DEFAULT UPPER('a'),
 u int NULL CONSTRAINT d20 DEFAULT ABS(-3),
 v bigint NULL CONSTRAINT d21 DEFAULT 3000000000,
 w date NULL CONSTRAINT d22 DEFAULT CONVERT(date, GETDATE()),
 x int NULL, y int NULL, z nvarchar(10) NULL,
 cc1 AS x + y * 2, cc2 AS (x + y) * 2, cc3 AS x - (y - 1),
 CONSTRAINT c1 CHECK (x > 0 AND y < 10),
 CONSTRAINT c2 CHECK (x IN (1, 2, 3)),
 CONSTRAINT c3 CHECK (x BETWEEN 1 AND 5),
 CONSTRAINT c4 CHECK (z LIKE 'a%'),
 CONSTRAINT c5 CHECK (x IS NULL OR y IS NOT NULL),
 CONSTRAINT c6 CHECK (NOT (x = 1)),
 CONSTRAINT c7 CHECK (x <> y),
 CONSTRAINT c8 CHECK (x != y),
 CONSTRAINT c9 CHECK (len(z) > 2),
 CONSTRAINT c10 CHECK (z IN ('a', 'b')),
 CONSTRAINT c11 CHECK (x >= -1),
 CONSTRAINT c12 CHECK (CASE WHEN x > 1 THEN 1 ELSE 0 END = 1),
 CONSTRAINT c13 CHECK (x NOT IN (1, 2)),
 CONSTRAINT c14 CHECK (x NOT BETWEEN 1 AND 2),
 CONSTRAINT c15 CHECK (z NOT LIKE 'a%'),
 CONSTRAINT c16 CHECK (x % 2 = 0),
 CONSTRAINT c17 CHECK ([x] > 0.5),
 CONSTRAINT c18 CHECK (z = N'Ab'),
 CONSTRAINT c19 CHECK (x > 0 AND (y > 0 OR z = 'a')),
 CONSTRAINT c20 CHECK (ISNULL(x, 0) >= 0),
 CONSTRAINT c21 CHECK (x * -1 < 0),
 CONSTRAINT c22 CHECK (COALESCE(x, y) > 0),
 CONSTRAINT c23 CHECK (x & 1 = 1),
 CONSTRAINT c24 CHECK (z <> ''),
 CONSTRAINT c25 CHECK ((x > 0 OR y > 0) AND z IS NOT NULL),
 CONSTRAINT c26 CHECK (x > 0 OR y > 0 AND z IS NULL));
CREATE INDEX ix_d ON dbo.d (x) WHERE x > 0 AND z IS NOT NULL;
-- @step batch
SELECT name, definition FROM sys.default_constraints ORDER BY name;
SELECT name, definition FROM sys.check_constraints ORDER BY name;
SELECT name, definition FROM sys.computed_columns ORDER BY name;
SELECT name, filter_definition FROM sys.indexes WHERE name = 'ix_d';
SELECT ORDINAL_POSITION, COLUMN_NAME, COLUMN_DEFAULT FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'd' AND COLUMN_DEFAULT IS NOT NULL ORDER BY ORDINAL_POSITION;
