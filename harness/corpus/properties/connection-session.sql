-- CONNECTIONPROPERTY (properties not tied to addresses) and
-- SESSIONPROPERTY, which follows SET options.
-- @step batch
SELECT p, CONNECTIONPROPERTY(p) AS v, SQL_VARIANT_PROPERTY(CONNECTIONPROPERTY(p), 'BaseType') AS bt,
       SQL_VARIANT_PROPERTY(CONNECTIONPROPERTY(p), 'MaxLength') AS ml
FROM (VALUES ('net_transport'), ('protocol_type'), ('auth_scheme'), ('physical_net_transport'), ('bogus'),
  ('NET_TRANSPORT')) AS x(p);
SELECT p, SESSIONPROPERTY(p) AS v, SQL_VARIANT_PROPERTY(SESSIONPROPERTY(p), 'BaseType') AS bt
FROM (VALUES ('ANSI_NULLS'), ('ANSI_PADDING'), ('ANSI_WARNINGS'), ('ARITHABORT'), ('CONCAT_NULL_YIELDS_NULL'),
  ('NUMERIC_ROUNDABORT'), ('QUOTED_IDENTIFIER'), ('bogus'), ('ansi_nulls')) AS x(p);
SELECT SESSIONPROPERTY(NULL) AS a, CONNECTIONPROPERTY(NULL) AS b;
-- @step batch
SET ARITHABORT OFF;
SELECT SESSIONPROPERTY('ARITHABORT') AS a, SESSIONPROPERTY('ANSI_WARNINGS') AS b;
SET ARITHABORT ON;
SELECT SESSIONPROPERTY('ARITHABORT') AS a, SESSIONPROPERTY('ANSI_WARNINGS') AS b;
-- @step batch
SELECT CONNECTIONPROPERTY();
