// node src/dump-checksum-keys.mjs: regenerates src/core/exec/checksum_unicode_data.mbt
// from the oracle. CHECKSUM of Unicode text under the version-0 Windows
// collations (Latin1_General_*, and nvarchar under SQL_Latin1_General_CP1_*)
// hashes the primary sort key bytes: 32-bit little-endian words folded with
// h = rotl3(h) ^ word, then the remaining bytes one by one with rotl3. The
// key of each UTF-16 unit is read back from CHECKSUM(NCHAR(n)) (c1) and
// CHECKSUM(NCHAR(n) + N'a') (c2; 'a' has the key 0E 02): a 2-byte key
// [s, w] gives c2 = 0x020E0000 | w << 8 | s and c1 = s << 3 ^ w, a 4-byte key
// K gives c1 = K, an empty key c1 = 0 and c2 = 114. Case and accents are not
// part of the hash (CI, CS, AI collations agree; checked in the query).
import { writeFile } from 'node:fs/promises'
import { oracleTarget, runCase } from './runner.mjs'

const sql = `SELECT value AS n, CHECKSUM(NCHAR(value)) AS c1, CHECKSUM(NCHAR(value) + N'a') AS c2,
  CHECKSUM(NCHAR(value) COLLATE Latin1_General_CS_AS) AS w1, CHECKSUM((NCHAR(value) + N'a') COLLATE Latin1_General_CI_AI) AS w2
FROM GENERATE_SERIES(0, 65535) ORDER BY value`
const t = await oracleTarget()
const r = await runCase(t, { steps: [{ kind: 'batch', sql, compare: true, params: [] }] })
t.stop?.()
const rows = r.steps[0].sets[0].rows
const U = v => v >>> 0
const rotl = (x, n) => ((x << n) | (x >>> (32 - n))) >>> 0
const keys = new Array(65536)
const special = []
for (const [n, c1s, c2s, w1, w2] of rows) {
  const c1 = U(c1s), c2 = U(c2s)
  if (c1 !== U(w1) || c2 !== U(w2)) throw new Error(`collations disagree at ${n}`)
  if (c1 === 0 && c2 === 114) { keys[n] = []; continue }
  if (c2 >>> 16 === 0x020e) {
    const s = c2 & 0xff, w = (c2 >>> 8) & 0xff
    // a trailing space-like unit is dropped (c1 = 0): U+0020, U+3000
    if (((s << 3) ^ w) === c1 || c1 === 0) { keys[n] = [s, w]; continue }
  }
  if ((rotl((rotl(c1, 3) ^ 0x0e) >>> 0, 3) ^ 0x02) >>> 0 === c2) {
    keys[n] = [c1 & 0xff, (c1 >>> 8) & 0xff, (c1 >>> 16) & 0xff, c1 >>> 24]
    continue
  }
  keys[n] = null // not decoded (6-byte ligature keys): CHECKSUM is not supported
}
// runs: [start, length, kind (0 empty, 2 two-byte, -1 unknown), s, w0, delta]
const runs = []
for (let i = 0; i < 65536;) {
  const k = keys[i]
  let j = i + 1
  if (k === null || k.length === 4) { i++; continue }
  if (k.length === 0) {
    while (j < 65536 && keys[j] && keys[j].length === 0) j++
    runs.push([i, j - i, 0, 0, 0, 0])
  } else {
    let d = null
    while (j < 65536 && keys[j] && keys[j].length === 2 && keys[j][0] === k[0]) {
      const dd = keys[j][1] - keys[j - 1][1]
      if (d === null) d = dd
      if (dd !== d) break
      j++
    }
    runs.push([i, j - i, 2, k[0], k[1], d ?? 0])
  }
  i = j
}
for (let i = 0; i < 65536; i++) if (keys[i] && keys[i].length === 4) special.push([i, keys[i].reduce((a, b, x) => a + b * 2 ** (8 * x), 0)])
const out = [
  '// Generated by harness/src/dump-checksum-keys.mjs from the oracle; do not edit.',
  '// Primary sort keys of UTF-16 units under the version-0 Windows collations,',
  '// as CHECKSUM hashes them (see checksum.mbt).',
  '',
  '///|',
  '/// (first unit, count, kind, script byte, first weight, weight step);',
  '/// kind 0: empty key (ignorable), 2: two bytes [script, weight]. Units in no',
  '/// run and not in checksum_key4 have no known key.',
  'let checksum_key_runs : Array[(Int, Int, Int, Int, Int, Int)] = [',
  ...runs.map(r => `  (${r.join(', ')}),`),
  ']',
  '',
  '///|',
  '/// Units with a 4-byte key (expansions such as ß = ss), as a little-endian word.',
  'let checksum_key4 : Array[(Int, Int64)] = [',
  ...special.map(([u, k]) => `  (${u}, ${k}L),`),
  ']',
  '',
]
await writeFile(new URL('../../src/core/exec/checksum_unicode_data.mbt', import.meta.url), out.join('\n'))
console.log('runs', runs.length, 'key4', special.length, 'unknown', keys.filter(k => k === null).length)
process.exit(0)
