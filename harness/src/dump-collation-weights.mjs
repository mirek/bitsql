// Dumps collation weight facts from SQL Server into
// src/core/types/collation_weights_data.mbt, for the version-0 tables
// (Latin1_General_*, SQL_Latin1_General_CP1_* on Unicode data) and the
// version-100 tables:
// - ignorable code units: N'a' + NCHAR(u) + N'b' = N'ab' under a
//   CS_AS_KS_WS collation (no level tells them apart), as ranges;
// - accent order: the dense rank of N'a' + NCHAR(m) for every combining
//   mark U+0300..U+036F under CS_AS (equal ranks are equal weights).
//
// Usage (in harness/): node src/dump-collation-weights.mjs ../src/core/types/collation_weights_data.mbt
// then `moon fmt`. Needs the oracle (npm run oracle:start).
import { writeFileSync } from 'node:fs'
import { oracleTarget, runCase } from './runner.mjs'

const output = process.argv[2]
if (!output) throw new Error('usage: dump-collation-weights.mjs <output.mbt>')
const tables = { 0: 'Latin1_General', 100: 'Latin1_General_100' }
const ignorableSql = `WITH n AS (SELECT TOP (65536) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) - 1 AS u FROM sys.all_columns a CROSS JOIN sys.all_columns b),
hit AS (
  SELECT 0 AS t, u FROM n WHERE (N'a' + NCHAR(u) + N'b') COLLATE ${tables[0]}_CS_AS_KS_WS = N'ab'
  UNION ALL SELECT 100, u FROM n WHERE (N'a' + NCHAR(u) + N'b') COLLATE ${tables[100]}_CS_AS_KS_WS = N'ab'),
g AS (SELECT t, u, u - ROW_NUMBER() OVER (PARTITION BY t ORDER BY u) AS k FROM hit)
SELECT t, MIN(u) AS lo, MAX(u) AS hi FROM g GROUP BY t, k ORDER BY t, lo`
const accentSql = version => `WITH n AS (SELECT TOP (112) 768 + ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) - 1 AS u FROM sys.all_columns)
SELECT u, DENSE_RANK() OVER (ORDER BY (N'a' + NCHAR(u)) COLLATE ${tables[version]}_CS_AS) AS r FROM n ORDER BY u`

const target = await oracleTarget({ log: () => {} })
const rows = async sql => {
  const result = await runCase(target, { id: 'collation-weights', steps: [{ kind: 'batch', sql }] })
  const step = result.steps[0]
  if (step.errors?.length) throw new Error(JSON.stringify(step.errors))
  return step.sets[0].rows
}
const ignorable = await rows(ignorableSql)
const accents = { 0: await rows(accentSql(0)), 100: await rows(accentSql(100)) }
await target.stop?.()

const list = (items, per) => {
  const lines = []
  for (let i = 0; i < items.length; i += per) lines.push(`  ${items.slice(i, i + per).join(', ')},`)
  return lines.join('\n')
}
const ranges = version => ignorable.filter(r => r[0] === version).map(r => `(${r[1]}, ${r[2]})`)
const ignorableBlock = version => `///|
/// Ignorable code unit ranges of the version-${version} tables (${ranges(version).length}).
let ignorable_v${version} : Array[(Int, Int)] = [
${list(ranges(version), 8)}
]
`
const accentBlock = version => `///|
/// Secondary (accent) rank of U+0300 + i in the version-${version} tables.
let accent_rank_v${version} : FixedArray[Int] = [
${list(accents[version].map(r => String(r[1])), 16)}
]
`
writeFileSync(output, `// Generated by harness/src/dump-collation-weights.mjs from SQL Server.
// Do not edit; rerun the dumper.

${ignorableBlock(0)}
${ignorableBlock(100)}
${accentBlock(0)}
${accentBlock(100)}`)
console.log(`wrote ${output}: ${ranges(0).length} + ${ranges(100).length} ignorable ranges, accent ranks`)
