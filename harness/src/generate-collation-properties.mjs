// Generate property lookup independently of the implemented comparison families.
import {readFileSync,writeFileSync} from 'node:fs';
const source=JSON.parse(readFileSync(new URL('../corpus/sql2025/collation-property-inventory.expected.json',import.meta.url)));
const rows=Object.values(source.cases).flatMap(c=>{
 const step=c.steps[0];
 if(step.errors.length || step.sets.length!==1) throw Error('invalid property capture');
 return step.sets[0].rows;
}).map(([name,...props])=>{
 if(typeof name!=='string'||props.length!==4||!props.every(Number.isInteger))throw Error('invalid property row');
 return [name.toUpperCase(),...props];
}).sort((a,b)=>a[0]<b[0]?-1:a[0]>b[0]?1:0);
if(rows.length!==5540||new Set(rows.map(r=>r[0])).size!==rows.length)throw Error('incomplete or duplicate inventory');
const text=rows.map(([name,...props])=>`  (${JSON.stringify(name)}, ${props.join(', ')}),`).join('\n');
writeFileSync(new URL('../../src/core/types/collation_property_data.mbt',import.meta.url),`// Generated by harness/src/generate-collation-properties.mjs from oracle captures.\n\n///|\nlet collation_property_data : Array[(String, Int, Int, Int, Int)] = [\n${text}\n]\n`);
console.log(`wrote ${rows.length} collation property entries`);
